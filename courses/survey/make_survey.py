def josa(label, a, b):
    """마지막 한글 글자(괄호 앞)에 받침이 있으면 a, 없으면 b."""
    base = re.sub(r'\([^)]*\)\s*$', '', label).strip()
    for ch in reversed(base):
        if '가' <= ch <= '힣':
            return a if (ord(ch) - 0xAC00) % 28 else b
    return a

